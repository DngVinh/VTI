export interface DomainValidationIssue {
  field: string;
  message: string;
}

export class QuestionBankDomainError extends Error {
  readonly code: QuestionBankErrorCode;
  readonly issues?: readonly DomainValidationIssue[];

  constructor(
    code: QuestionBankErrorCode,
    message: string,
    issues?: readonly DomainValidationIssue[]
  ) {
    super(message);
    this.name = 'QuestionBankDomainError';
    this.code = code;
    this.issues = issues;
  }
}
